/** Punctuation stripped before a dictionary lookup. */
export const TOKEN_PUNCT = /[.,!?"«»“”—–:;()…]/g;

export const cleanToken = (token: string) =>
  token.replace(TOKEN_PUNCT, '').replace(/[\u2018\u2019]/g, "'").toLowerCase();

export function glossaryFor(token: string): GlossaryEntry | undefined {
  return BOOK_GLOSSARY[cleanToken(token)];
}
